SELECT c.NumeroConcurso, c.D1, c.D2, c.D3, c.D4, c.D5, c.D6, c.D7,
       c.D8, c.D9, c.D10, c.D11, c.D12, c.D13, c.D14, c.D15
FROM Concursos c
JOIN Loterias l ON l.Id = c.LoteriaId
WHERE l.Nome = 'Lotofácil'
  AND (c.D1 NOT BETWEEN 1 AND 25
    OR c.D2 NOT BETWEEN 1 AND 25
    OR c.D3 NOT BETWEEN 1 AND 25
    OR c.D4 NOT BETWEEN 1 AND 25
    OR c.D5 NOT BETWEEN 1 AND 25
    OR c.D6 NOT BETWEEN 1 AND 25
    OR c.D7 NOT BETWEEN 1 AND 25
    OR c.D8 NOT BETWEEN 1 AND 25
    OR c.D9 NOT BETWEEN 1 AND 25
    OR c.D10 NOT BETWEEN 1 AND 25
    OR c.D11 NOT BETWEEN 1 AND 25
    OR c.D12 NOT BETWEEN 1 AND 25
    OR c.D13 NOT BETWEEN 1 AND 25
    OR c.D14 NOT BETWEEN 1 AND 25
    OR c.D15 NOT BETWEEN 1 AND 25);